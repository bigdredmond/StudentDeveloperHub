# Connect to the Neon PostgreSQL database
def get_db():
    database_url = os.environ.get("DATABASE_URL")

    if not database_url:
        raise RuntimeError(
            "DATABASE_URL environment variable is not configured."
        )

    conn = psycopg.connect(
        database_url,
        row_factory=dict_row
    )

    return conn


