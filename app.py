@app.route("/quiz", methods=["GET", "POST"])
def quiz():
    if "student_id" not in session:
        return redirect("/login")

    conn = get_db()
    try:
        student = conn.execute(
            "SELECT id FROM students WHERE id = %s",
            (session["student_id"],)
        ).fetchone()
    finally:
        conn.close()

    if student is None:
        session.clear()
        return redirect("/login")

    if request.method == "POST":
        questions = session.get("quiz_questions")

        if not questions or len(questions) != 20:
            session.pop("quiz_questions", None)
            return redirect("/quiz")

        score = 0
        results = []

        for i, question in enumerate(questions, start=1):
            selected = request.form.get(f"q{i}", "")
            correct = selected == question["answer"]

            if correct:
                score += 1

            results.append({
                "number": i,
                "question": question["question"],
                "selected": selected,
                "correct_answer": question["answer"],
                "options": question["options"],
                "is_correct": correct,
                "explanation": question["explanation"]
            })

        percentage = round((score / len(questions)) * 100)

        conn = get_db()
        try:
            conn.execute(
                """INSERT INTO quiz_results
                   (student_id, score, percentage)
                   VALUES (%s, %s, %s)""",
                (session["student_id"], score, percentage)
            )
            conn.commit()
        finally:
            conn.close()

        session.pop("quiz_questions", None)

        if score == 20:
            feedback = "Excellent! You answered every question correctly!"
        elif score >= 15:
            feedback = "Very good work! Keep practising."
        elif score >= 10:
            feedback = "Good effort! Review your lessons and try again."
        else:
            feedback = "Keep learning! Review your materials and try again."

        return render_template(
            "quiz.html",
            questions=questions,
            results=results,
            score=score,
            percentage=percentage,
            feedback=feedback
        )

    questions = random.sample(PYTHON_QUESTIONS, 20)
    session["quiz_questions"] = questions

    return render_template(
        "quiz.html",
        questions=questions
    )
