@app.route("/learn/<topic>")
def learn(topic):
    if "student_id" not in session:
        return redirect("/login")

    page = learning_pages.get(topic)

    if page is None:
        return redirect("/materials")

    conn = get_db()

    try:
        student = conn.execute(
            "SELECT id FROM students WHERE id = %s",
            (session["student_id"],)
        ).fetchone()

        if student is None:
            session.clear()
            return redirect("/login")

        rows = conn.execute(
            """
            SELECT lesson_index
            FROM lesson_progress
            WHERE student_id = %s AND topic = %s
            """,
            (student["id"], topic)
        ).fetchall()

        completed_lessons = {
            row["lesson_index"] for row in rows
        }

    finally:
        conn.close()

    for index, lesson in enumerate(page["lessons"]):
        if index < 7:
            lesson["level"] = "Beginner"
        elif index < 14:
            lesson["level"] = "Intermediate"
        else:
            lesson["level"] = "Advanced"
    total_lessons = len(page["lessons"])
    completed_count = len(completed_lessons)

    return render_template(
        "learning.html",
        page=page,
        topic=topic,
        completed_lessons=completed_lessons,
        completed_count=completed_count,
        total_lessons=total_lessons,
        progress_percentage=round(
            completed_count / total_lessons * 100
        ) if total_lessons else 0
    )
@app.route("/complete-lesson/<topic>/<int:lesson_index>", methods=["POST"])
def complete_lesson(topic, lesson_index):
    if "student_id" not in session:
        return redirect("/login")

    page = learning_pages.get(topic)

    if page is None:
        return redirect("/materials")

    if lesson_index < 0 or lesson_index >= len(page["lessons"]):
        return redirect(f"/learn/{topic}")

    conn = get_db()

    try:
        student = conn.execute(
            "SELECT id FROM students WHERE id = %s",
            (session["student_id"],)
        ).fetchone()

        if student is None:
            session.clear()
            return redirect("/login")

        conn.execute("""
            INSERT INTO lesson_progress
                (student_id, topic, lesson_index)
            VALUES (%s, %s, %s)
            ON CONFLICT (student_id, topic, lesson_index)
            DO NOTHING
        """, (session["student_id"], topic, lesson_index))
        conn.commit()

    finally:
        conn.close()

    return redirect(f"/learn/{topic}")

@app.route("/admin", methods=["GET", "POST"])
def admin_login():
    message = ""

    if request.method == "POST":
        username = request.form.get("username", "")
        password = request.form.get("password", "")

        admin_password = app.config["ADMIN_PASSWORD"]

        if (
            admin_password
            and username == app.config["ADMIN_USERNAME"]
            and password == admin_password
        ):
            session.clear()
            session["is_admin"] = True
            return redirect("/admin/dashboard")

        message = "Invalid admin credentials or admin password not configured."

    return render_template("admin_login.html", message=message)


